import assert from 'node:assert/strict';
import { test } from 'node:test';

import {
  classifyFile,
  detectFreezeViolations,
  summarize,
  verdict,
  type DiffEntry,
} from '../../tools/check-change-budget.ts';

function entry(path: string, status: DiffEntry['status'], added: number, deleted: number, fileClass: DiffEntry['fileClass']): DiffEntry {
  return { path, status, added, deleted, fileClass };
}

test('classifies generated files before path rules', () => {
  assert.equal(classifyFile('services/control-plane/ent/mutation.go', '// Code generated by ent, DO NOT EDIT.'), 'generated');
  assert.equal(classifyFile('packages/contracts/go/api/internal.pb.go', '// Code generated by protoc-gen-go. DO NOT EDIT.'), 'generated');
});

test('classifies tests by path and basename', () => {
  assert.equal(classifyFile('tests/ui/console.test.ts', ''), 'test');
  assert.equal(classifyFile('services/control-plane/internal/server/server_test.go', ''), 'test');
  assert.equal(classifyFile('services/fabric/internal/fabric/service.go', ''), 'code');
  assert.equal(classifyFile('docs/policies/change-budget.md', ''), 'doc');
});

test('summarizes additions and deletions per class', () => {
  const summary = summarize([
    entry('a.go', 'M', 100, 40, 'code'),
    entry('b_test.go', 'A', 50, 0, 'test'),
    entry('c.pb.go', 'M', 30, 10, 'generated'),
    entry('d.md', 'A', 5, 0, 'doc'),
  ]);
  assert.equal(summary.codeAdded, 100);
  assert.equal(summary.codeDeleted, 40);
  assert.equal(summary.netCode, 60);
  assert.equal(summary.testAdded, 50);
  assert.equal(summary.generatedAdded, 30);
  assert.equal(summary.newFiles, 2);
});

test('flags freeze-list violations', () => {
  const violations = detectFreezeViolations(
    [
      entry('services/ledger/internal/ledger/wallet_receipt.go', 'A', 10, 0, 'code'),
      entry('services/control-plane/ent/schema/refund.go', 'A', 10, 0, 'code'),
      entry('.github/workflows/extra.yml', 'A', 10, 0, 'other'),
      entry('docs/spec/target/new_spec.md', 'A', 10, 0, 'doc'),
      entry('services/serve/cmd/extra/main.go', 'A', 10, 0, 'code'),
    ],
    3,
  );
  const rules = violations.map((violation) => violation.rule).sort();
  assert.deepEqual(rules, [
    'new-abstraction-file',
    'new-binary',
    'new-ent-schema',
    'new-rpc',
    'new-target-spec',
    'new-workflow',
  ]);
});

test('does not flag a new file in an existing abstraction package', () => {
  const violations = detectFreezeViolations(
    [entry('services/fabric/coordination/extra.go', 'A', 10, 0, 'code')],
    0,
    new Set<string>(),
  );
  assert.deepEqual(violations, []);
});

test('warns on growth without a deletion budget', () => {
  const summary = summarize([entry('a.go', 'M', 400, 50, 'code')]);
  const result = verdict(summary, [], { enforce: false, exception: false });
  assert.equal(result.level, 'warn');
});

test('fails on a freeze violation only when enforcing', () => {
  const summary = summarize([entry('a.go', 'M', 10, 10, 'code')]);
  const violations = detectFreezeViolations([entry('services/x/reconcile.go', 'A', 10, 0, 'code')], 0);
  assert.equal(verdict(summary, violations, { enforce: false, exception: false }).level, 'warn');
  assert.equal(verdict(summary, violations, { enforce: true, exception: false }).level, 'fail');
  assert.equal(verdict(summary, violations, { enforce: true, exception: true }).level, 'warn');
});
