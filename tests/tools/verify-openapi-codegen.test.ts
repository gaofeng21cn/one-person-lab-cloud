import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";
import type { TestContext } from "node:test";
import { parse as parseYAML } from "yaml";
import {
  OAPI_CODEGEN_CONFIG,
  OPENAPI_GO_OUTPUT,
  OPENAPI_SOURCE,
  OPENAPI_TS_OUTPUT,
  normalizeOpenAPIDocument,
  verifyOpenAPICodegen
} from "../../tools/verify-openapi-codegen.ts";

function put(root: string, rel: string, data: string) {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), data, "utf8");
}

function makeFixture(t: TestContext) {
  const root = mkdtempSync(join(tmpdir(), "opl-openapi-codegen-test-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  put(root, OPENAPI_SOURCE, [
    "openapi: 3.0.3",
    "info:",
    "  title: test",
    "  version: 1.0.0",
    "x-operator-presentation-schemas:",
    "  OperatorWorkspaceSourcePage:",
    "    type: object",
    "    properties:",
    "      source:",
    "        type: string",
    "paths:",
    "  /api/v2/operator/workspaces:",
    "    get:",
    "      responses:",
    "        '200':",
    "          description: ok",
    "          content:",
    "            application/json:",
    "              schema:",
    "                $ref: '#/x-operator-presentation-schemas/OperatorWorkspaceSourcePage'",
    "components:",
    "  schemas:",
    "    Error:",
    "      type: object",
    ""
  ].join("\n"));
  put(root, OAPI_CODEGEN_CONFIG, "package: openapi\noutput: types.go\n");
  return root;
}

test("normalizeOpenAPIDocument hoists non-component x- schema references into components.schemas", () => {
  const raw = [
    "openapi: 3.0.3",
    "x-operator-presentation-schemas:",
    "  DemoPage:",
    "    type: object",
    "paths:",
    "  /demo:",
    "    get:",
    "      responses:",
    "        '200':",
    "          content:",
    "            application/json:",
    "              schema:",
    "                $ref: '#/x-operator-presentation-schemas/DemoPage'",
    "components:",
    "  schemas: {}",
    ""
  ].join("\n");
  const parsed = parseYAML(normalizeOpenAPIDocument(raw)) as any;
  assert.deepEqual(parsed.components.schemas.DemoPage, { type: "object" });
  assert.equal(
    parsed.paths["/demo"].get.responses["200"].content["application/json"].schema.$ref,
    "#/components/schemas/DemoPage"
  );
});

test("verifyOpenAPICodegen passes when checked-in TS and Go outputs match generated bytes and fails on drift", async (t) => {
  const root = makeFixture(t);
  const generators = {
    generateTS: async (specPath: string) => `// ts:${readFileSync(specPath, "utf8").length}\n`,
    generateGo: (_root: string, specPath: string) => `// go:${readFileSync(specPath, "utf8").length}\n`
  };

  const written = await verifyOpenAPICodegen({ root, write: true, generators });
  assert.equal(written.passed, true, written.errors.join("\n"));

  const fresh = await verifyOpenAPICodegen({ root, generators });
  assert.equal(fresh.passed, true, fresh.errors.join("\n"));
  assert.deepEqual(fresh.compared, [OPENAPI_TS_OUTPUT, OPENAPI_GO_OUTPUT].sort());

  put(root, OPENAPI_TS_OUTPUT, "// tampered\n");
  const drifted = await verifyOpenAPICodegen({ root, generators });
  assert.equal(drifted.passed, false);
  assert.deepEqual(drifted.errors, [`OpenAPI generated bytes differ: ${OPENAPI_TS_OUTPUT}`]);
});
