import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse as parseYAML, stringify as stringifyYAML } from "yaml";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const OAPI_CODEGEN_VERSION = "v2.9.0";
export const OPENAPI_SOURCE = "docs/spec/target/03_api_contract_complete.yaml";
export const OAPI_CODEGEN_CONFIG = "packages/contracts/openapi/oapi-codegen.yaml";
export const OPENAPI_TS_OUTPUT = "apps/console-ui/src/api/openapi.generated.ts";
export const OPENAPI_GO_OUTPUT = "packages/contracts/go/openapi/types_generated.go";

export const openAPIInputs = [
  OPENAPI_SOURCE,
  OAPI_CODEGEN_CONFIG,
  "tools/verify-openapi-codegen.ts"
] as const;

export const openAPIOutputs = [
  OPENAPI_TS_OUTPUT,
  OPENAPI_GO_OUTPUT
] as const;

let tsHookRegistered = false;

function ensureLegacyTypeScriptHook() {
  if (tsHookRegistered) return;
  tsHookRegistered = true;
  registerHooks({
    resolve(specifier, context, nextResolve) {
      if (specifier === "typescript" && context.parentURL?.includes("/openapi-typescript/")) {
        return nextResolve("typescript-legacy-ast", context);
      }
      return nextResolve(specifier, context);
    }
  });
}

/**
 * Hoists non-component top-level `x-*` schema maps referenced via `#/x-.../<Name>`
 * (currently `x-operator-presentation-schemas`) into `components.schemas` so both
 * `openapi-typescript` and `oapi-codegen/v2` receive standard OpenAPI 3.0.3 refs
 * without modifying the checked-in contract file.
 */
export function normalizeOpenAPIDocument(rawYAML: string): string {
  const doc = parseYAML(rawYAML) as Record<string, unknown>;
  const nonComponentRefs = new Set<string>();
  const scan = (node: unknown) => {
    if (!node || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (const item of node) scan(item);
      return;
    }
    for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
      if (key === "$ref" && typeof value === "string" && value.startsWith("#/x-")) {
        nonComponentRefs.add(value);
      } else {
        scan(value);
      }
    }
  };
  scan(doc);

  const components = ((doc.components ??= {}) as Record<string, unknown>);
  const schemas = ((components.schemas ??= {}) as Record<string, unknown>);
  for (const ref of [...nonComponentRefs].sort()) {
    const segments = ref.slice(2).split("/");
    if (segments.length !== 2) {
      throw new Error(`unsupported non-component OpenAPI $ref: ${ref}`);
    }
    const [section, name] = segments;
    const container = doc[section] as Record<string, unknown> | undefined;
    if (!container || !(name in container)) {
      throw new Error(`unresolved non-component OpenAPI $ref: ${ref}`);
    }
    if (!(name in schemas)) {
      schemas[name] = container[name];
    }
  }

  const rewrite = (node: unknown): unknown => {
    if (!node || typeof node !== "object") return node;
    if (Array.isArray(node)) return node.map(rewrite);
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
      if (key === "$ref" && typeof value === "string" && value.startsWith("#/x-")) {
        const name = value.slice(2).split("/")[1];
        out[key] = `#/components/schemas/${name}`;
      } else {
        out[key] = rewrite(value);
      }
    }
    return out;
  };

  return stringifyYAML(rewrite(doc), { lineWidth: 0 });
}

export async function generateOpenAPITypescript(normalizedSpecPath: string): Promise<string> {
  ensureLegacyTypeScriptHook();
  const { default: openapiTS, astToString } = await import("openapi-typescript");
  const ast = await openapiTS(pathToFileURL(normalizedSpecPath));
  return [
    "// Code generated by openapi-typescript from docs/spec/target/03_api_contract_complete.yaml; DO NOT EDIT.",
    "// Regenerate with: npm run generate:openapi",
    "",
    astToString(ast)
  ].join("\n");
}

function resolveOapiCodegenCommand(configPath: string, normalizedSpecPath: string): { command: string; args: string[] } {
  const probe = spawnSync("oapi-codegen", ["--version"], { encoding: "utf8" });
  if (!probe.error && probe.status === 0 && probe.stdout.includes(OAPI_CODEGEN_VERSION)) {
    return { command: "oapi-codegen", args: ["-config", configPath, normalizedSpecPath] };
  }
  return {
    command: "go",
    args: [
      "run",
      `github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@${OAPI_CODEGEN_VERSION}`,
      "-config",
      configPath,
      normalizedSpecPath
    ]
  };
}

export function generateOpenAPIGo(root: string, normalizedSpecPath: string, outPath: string): string {
  const baseConfig = parseYAML(readFileSync(join(root, OAPI_CODEGEN_CONFIG), "utf8")) as Record<string, unknown>;
  const tempConfigPath = join(dirname(outPath), "oapi-codegen.temp.yaml");
  writeFileSync(tempConfigPath, stringifyYAML({ ...baseConfig, output: outPath }));
  const { command, args } = resolveOapiCodegenCommand(tempConfigPath, normalizedSpecPath);
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    timeout: 180_000,
    maxBuffer: 16 * 1024 * 1024
  });
  if (result.error || result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed: ${result.error?.message ?? result.signal ?? result.status}\n${result.stderr}${result.stdout}`.trim());
  }
  return readFileSync(outPath, "utf8");
}

export type OpenAPIGenerators = {
  generateTS?: (normalizedSpecPath: string) => Promise<string>;
  generateGo?: (root: string, normalizedSpecPath: string, outPath: string) => string;
};

export async function verifyOpenAPICodegen({
  root = repositoryRoot,
  write = false,
  generators = {}
}: { root?: string; write?: boolean; generators?: OpenAPIGenerators } = {}) {
  const temporary = mkdtempSync(join(tmpdir(), "opl-openapi-codegen-"));
  const errors: string[] = [];
  const compared: string[] = [];
  try {
    const rawSpec = readFileSync(join(root, OPENAPI_SOURCE), "utf8");
    const normalizedSpecPath = join(temporary, "03_api_contract_complete.normalized.yaml");
    writeFileSync(normalizedSpecPath, normalizeOpenAPIDocument(rawSpec), "utf8");

    const genTS = generators.generateTS ?? generateOpenAPITypescript;
    const genGo = generators.generateGo ?? generateOpenAPIGo;

    const regenerated = new Map<string, Buffer>();
    try {
      const tsSource = await genTS(normalizedSpecPath);
      regenerated.set(OPENAPI_TS_OUTPUT, Buffer.from(tsSource, "utf8"));
    } catch (error) {
      errors.push(`openapi-typescript failed: ${error instanceof Error ? error.message : String(error)}`);
    }
    try {
      const tempGoOut = join(temporary, "types_generated.go");
      const goSource = genGo(root, normalizedSpecPath, tempGoOut);
      regenerated.set(OPENAPI_GO_OUTPUT, Buffer.from(goSource, "utf8"));
    } catch (error) {
      errors.push(`oapi-codegen failed: ${error instanceof Error ? error.message : String(error)}`);
    }

    if (write) {
      if (errors.length > 0) {
        return { passed: false, errors, compared };
      }
      for (const [relPath, bytes] of regenerated) {
        const dest = join(root, relPath);
        mkdirSync(dirname(dest), { recursive: true });
        writeFileSync(dest, bytes);
        compared.push(relPath);
      }
      return { passed: true, errors, compared: compared.sort() };
    }

    for (const relPath of [...openAPIOutputs].sort()) {
      const checkedIn = join(root, relPath);
      const bytes = regenerated.get(relPath);
      if (!bytes) continue;
      if (!existsSync(checkedIn)) {
        errors.push(`missing checked-in OpenAPI generated output: ${relPath}`);
      } else if (!readFileSync(checkedIn).equals(bytes)) {
        errors.push(`OpenAPI generated bytes differ: ${relPath}`);
      } else {
        compared.push(relPath);
      }
    }
    return { passed: errors.length === 0, errors, compared };
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  const write = args.includes("--write");
  if (args.length > 1 || (args.length === 1 && !write)) {
    console.error("usage: verify-openapi-codegen.ts [--write]");
    process.exit(1);
  }
  const result = await verifyOpenAPICodegen({ write });
  for (const path of result.compared) console.log(`${write ? "WROTE" : "MATCH"}: ${path}`);
  for (const error of result.errors) console.error(`FAIL: ${error}`);
  console.log(`OpenAPI codegen ${write ? "generation" : "freshness"}: ${result.passed ? "PASS" : "FAIL"}`);
  process.exitCode = result.passed ? 0 : 1;
}
